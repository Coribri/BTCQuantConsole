const assert=require('node:assert/strict');
const {estimate,rules,status}=require('../btcquant/static/quant-guide.js');
const state={price:100,account:{wallet:10000,equity:10000,usdt_free:10000}},model={risk_fraction:.005},signal={atr14:2},settings={risk_fraction:.005,leverage:5};
const config={fee_rate:.0005,slippage_bps:2,mmr:.005};
let r=estimate({state,model,signal,settings,config,futures:true});
assert.equal(r.budget,50);assert.ok(r.loss<=50.0000001);assert.equal(r.longStop,95);assert.equal(r.shortStop,105);assert.ok(r.notional<=10000);assert.ok(r.margin<=2500);
r=estimate({state,model,signal,settings,config,futures:false});assert.ok(r.notional<=2500);assert.ok(r.loss<=50.0000001);
r=estimate({state:{...state,account:{...state.account,usdt_free:10}},model,signal,settings,config,futures:false});assert.equal(r.notional,10);
assert.equal(estimate({state,model,signal:{},settings,config,futures:true}).valid,false);
assert.equal(estimate({state,model,signal,settings,config:{},futures:true}).valid,false);
assert.equal(estimate({state,model,signal,settings:{...settings,leverage:100},config,futures:true}).valid,false);
assert.match(rules({parameters:{trailing_enabled:false,fast:12,slow:50,regime:160}},false,'4h').protection,/已关闭/);
assert.match(rules(model,false,'4h').protection,/移动止盈/);
assert.doesNotMatch(rules(model,false,'4h').protection,/初始止损/);
assert.match(rules(model,true,'4h').protection,/初始止损/);
assert.match(rules({kind:'http'},true,'1h').entry,/外部程序/);
assert.match(rules({ai_mode:'agent'},true,'1h').entry,/AI/);
assert.match(status({conditions:[{label:'避免过度追价',long:false,short:true}]},'long',false),/避免过度追价/);
assert.match(status({},'short',false),/正在获取/);
console.log('Risk estimates, caps, missing data and model-specific explanations passed.');
